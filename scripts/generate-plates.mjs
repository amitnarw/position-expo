import { Resvg } from '@resvg/resvg-js';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { poseToScene } from '../src/art/body.ts';
import { poses } from '../src/art/poses.ts';
import { positions } from '../src/content/positions.ts';
import { palettes } from '../src/theme/tokens.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outputDir = join(root, 'assets', 'plates');
mkdirSync(outputDir, { recursive: true });

const SIZE = 720;
const STROKE = 5.5;
const SCHEMES = ['light', 'dark'];

function mix(a, b, t) {
  const parse = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
  const [ar, ag, ab] = parse(a);
  const [br, bg, bb] = parse(b);
  const channel = (x, y) => Math.round(x + (y - x) * t).toString(16).padStart(2, '0');
  return `#${channel(ar, br)}${channel(ag, bg)}${channel(ab, bb)}`;
}

function sceneSvg(pose, scheme) {
  const palette = palettes[scheme];
  // Flat ground: the art sits on the same tone as the card it lives in, so the
  // tile reads as one borderless surface. No gradient at build time either.
  const ground = palette.surface;

  const base = (figure) => (figure.tone === 'clay' ? palette.clay : palette.ink);
  const tone = (figure) =>
    figure.depth === 'back' ? mix(base(figure), ground, 0.5) : base(figure);

  const scene = poseToScene(pose, 1000);
  const body = scene.figures
    .map((figure) => {
      const color = tone(figure);
      return (
        figure.halo.map((d) => `<path d="${d}" fill="${ground}" />`).join('') +
        figure.body
          .map(
            (d) =>
              `<path d="${d}" fill="${ground}" stroke="${color}" stroke-width="${STROKE}" stroke-linejoin="round" stroke-linecap="round" />`,
          )
          .join('')
      );
    })
    .join('');

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${SIZE}" height="${SIZE}" viewBox="0 0 1000 1000">
    <rect width="1000" height="1000" fill="${ground}" />
    ${body}
  </svg>`;
}

const manifest = [];

for (const position of positions) {
  const pose = poses[position.pose];
  if (!pose) {
    throw new Error(`Missing pose for ${position.slug} (${position.pose})`);
  }

  const entry = { slug: position.slug };
  for (const scheme of SCHEMES) {
    const file = `${position.slug}-${scheme}.png`;
    const png = new Resvg(sceneSvg(pose, scheme), {
      fitTo: { mode: 'width', value: SIZE },
    })
      .render()
      .asPng();
    writeFileSync(join(outputDir, file), png);
    entry[scheme] = file;
  }
  manifest.push(entry);
}

const lines = manifest.map(
  (entry) =>
    `  '${entry.slug}': {\n    light: require('../../assets/plates/${entry.light}'),\n    dark: require('../../assets/plates/${entry.dark}'),\n  },`,
);

const source = `// AUTO-GENERATED by scripts/generate-plates.mjs — do not edit by hand.
import type { ImageSourcePropType } from 'react-native';

import type { Scheme } from '@/theme/tokens';

export const plateImages: Record<string, Record<Scheme, ImageSourcePropType>> = {
${lines.join('\n')}
};

export function plateImage(slug: string, scheme: Scheme): ImageSourcePropType | undefined {
  return plateImages[slug]?.[scheme];
}
`;

writeFileSync(join(root, 'src', 'art', 'plate-images.ts'), source);

console.log(`Rendered ${positions.length} plates × ${SCHEMES.length} schemes at ${SIZE}px`);
